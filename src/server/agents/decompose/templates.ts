type TemplateSource = { title: string; description: string };

/** Прототип `pickTemplate`: перше збігле правило за назвою, описом і уточненням. */
export const pickTemplate = (task: TemplateSource, clarification?: string): TemplateKey => {
  const text = `${task.title} ${task.description} ${clarification ?? ""}`.toLowerCase();
  if (/e2e|тест|test/.test(text)) return "tests";
  if (/витік|флакі|падає|виправ|bug|fix|помилк/.test(text)) return "bug";
  if (/оновити|міграц|upgrade|next\.js/.test(text)) return "upgrade";
  if (/api|endpoint|rate|пагінац|middleware/.test(text)) return "api";
  return "generic";
};

/** Питання demo-режиму: для задач про тести — з прототипу, для інших — загальні. */
export const clarifyQuestions = (task: TemplateSource): string[] =>
  pickTemplate(task) === "tests"
    ? ["Що саме не так: падають, повільні чи їх немає?", "Які тести: unit, e2e чи всі? Є приклад падіння?"]
    : ["Який результат вважатимемо готовим?", "Що вже відомо або спробувано?"];
